#!/usr/bin/env node
// Writes src/builtin/rubric.ts: the review rubric (`packages/engine/src/rubric/`) as
// `builtin:reviewer`'s reference docs. Run after changing a rubric file:
//   pnpm --filter @omniralph/tasks generate:rubric
// (`@omniralph/engine`'s builtin review test fails while the two disagree.)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const rubric = new URL("../../engine/src/rubric/", import.meta.url);
const read = (path) => readFileSync(new URL(path, rubric), "utf8").trim();
const languages = readdirSync(new URL("languages/", rubric))
  .filter((name) => name.endsWith(".md"))
  .sort();
const docs = [
  { name: "rubric/universal.md", content: read("universal.md") },
  ...languages.map((name) => ({
    name: `rubric/languages/${name}`,
    content: read(`languages/${name}`),
  })),
];

const entries = docs
  .map(
    (doc) =>
      `  {\n    name: ${JSON.stringify(doc.name)},\n    content: ${JSON.stringify(doc.content)},\n  },`,
  )
  .join("\n");
const target = new URL("../src/builtin/rubric.ts", import.meta.url);
const source = `// Generated by scripts/generate-rubric.mjs from packages/engine/src/rubric/: don't edit.
import type { NamedContent } from "../definitions.js";

/**
 * The review rubric: \`rubric/universal.md\` (every review) and
 * \`rubric/languages/<language>.md\` (per language of the reviewed files; see
 * \`languagesForPaths\` in \`@omniralph/engine\`), trimmed.
 */
export const RUBRIC_DOCS: readonly NamedContent[] = [
${entries}
];
`;
const filepath = fileURLToPath(target);
const options = (await prettier.resolveConfig(filepath)) ?? {};
writeFileSync(target, await prettier.format(source, { ...options, filepath }));
