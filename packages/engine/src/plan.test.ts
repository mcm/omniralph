import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { parseDiff } from "./diff.js";
import { BUDGET_FILL_RATIO, createPathFilter, isTestPath, planChecks, planReview } from "./plan.js";
import { estimateTokens } from "./tokens.js";

const fixture = (name: string) =>
  parseDiff(readFileSync(new URL(`../test/fixtures/${name}.diff`, import.meta.url), "utf8"));

const ROOMY = { maxTokensPerReview: 1_000_000, maxFiles: 100 };

// budget.diff token estimates (ceil(patch chars / 3.5)) and risk weights:
//   docs/notes.md 1807 (1), test/e2e.ts 387 (1), src/lib/big-table.ts 5470 (2),
//   src/lib/format.ts 569 (2), src/handlers/order.ts 1104 (3),
//   src/api/users.ts 3638 (4), src/auth/login.ts 746 (5). Total 13721.
const budgetFiles = fixture("budget");

describe("planReview", () => {
  it("returns a single task with every included file and the full budget", () => {
    const plan = planReview(fixture("basic"), { maxTokensPerReview: 50_000, maxFiles: 25 });
    expect(plan.tasks).toHaveLength(1);
    expect(plan.tasks[0]?.id).toBe("task-1");
    expect(plan.tasks[0]?.budget).toBe(50_000);
    expect(plan.tasks[0]?.files.map((f) => f.path)).toEqual([
      "src/app.ts",
      "src/new.ts",
      "src/old.ts",
      "src/tail.txt",
    ]);
    expect(plan.skipped).toEqual([]);
    expect(plan.estimatedInputTokens).toBe(
      fixture("basic").reduce((sum, f) => sum + estimateTokens(f.patch), 0),
    );
  });

  it("skips built-in excluded paths at any depth", () => {
    const plan = planReview(fixture("excluded"), ROOMY);
    expect(
      plan.skipped
        .filter((s) => s.reason === "excluded")
        .map((s) => s.path)
        .sort(),
    ).toEqual([
      "apps/web/Cargo.lock",
      "apps/web/package-lock.json",
      "dist/index.js",
      "package-lock.json",
      "packages/web/dist/app.js",
      "pnpm-lock.yaml",
      "public/app.min.js",
      "public/style.min.css",
      "src/__snapshots__/a.test.ts.snap",
      "vendor/lib/x.go",
      "yarn.lock",
    ]);
    expect(plan.skipped).toContainEqual({ path: "src/gen/api.generated.ts", reason: "generated" });
    expect(plan.tasks[0]?.files.map((f) => f.path).sort()).toEqual([
      ".github/workflows/ci.yml",
      "docs/guide.md",
      "src/index.ts",
    ]);
  });

  it("skips generated files by path or by a generator marker at the top", () => {
    const added = (path: string, lines: string[]) =>
      [
        `diff --git a/${path} b/${path}`,
        "new file mode 100644",
        "index 0000000..1111111",
        "--- /dev/null",
        `+++ b/${path}`,
        `@@ -0,0 +1,${lines.length} @@`,
        ...lines.map((l) => `+${l}`),
        "",
      ].join("\n");
    const files = parseDiff(
      [
        added("api/user.pb.go", ["package api"]),
        added("py/user_pb2.py", ["x = 1"]),
        added("web/__generated__/types.ts", ["export type A = 1;"]),
        added("go/stringer.go", ["// Code generated by stringer; DO NOT EDIT.", "package go"]),
        added("js/schema.ts", ["/**", " * @generated", " */", "export {};"]),
        added("src/late.ts", ["a", "b", "c", "d", "e", "// @generated below the header"]),
        added("src/app.ts", ["export const a = 1;"]),
      ].join(""),
    );
    const plan = planReview(files, ROOMY);
    expect(plan.skipped).toEqual([
      { path: "api/user.pb.go", reason: "generated" },
      { path: "py/user_pb2.py", reason: "generated" },
      { path: "web/__generated__/types.ts", reason: "generated" },
      { path: "go/stringer.go", reason: "generated" },
      { path: "js/schema.ts", reason: "generated" },
    ]);
    expect(plan.tasks[0]?.files.map((f) => f.path)).toEqual(["src/late.ts", "src/app.ts"]);
  });

  it("skips repo pathExcludes (gitignore-like globs)", () => {
    const plan = planReview(fixture("excluded"), ROOMY, {
      pathExcludes: ["*.generated.ts", "docs/**", " "],
    });
    expect(plan.tasks[0]?.files.map((f) => f.path).sort()).toEqual([
      ".github/workflows/ci.yml",
      "src/index.ts",
    ]);
    expect(plan.skipped).toContainEqual({ path: "docs/guide.md", reason: "excluded" });
    expect(plan.skipped).toContainEqual({ path: "src/gen/api.generated.ts", reason: "excluded" });
  });

  it("skips binary files and files without hunks", () => {
    const plan = planReview(fixture("renames-binary"), ROOMY);
    expect(plan.skipped).toEqual([
      { path: "bin.dat", reason: "binary" },
      { path: "mode.sh", reason: "no_changes" },
      { path: "new name ä.txt", reason: "no_changes" },
      { path: "newbin.bin", reason: "binary" },
    ]);
    expect(plan.tasks[0]?.files.map((f) => f.path)).toEqual(["big.txt", "copy.txt", "gone.txt"]);
  });

  it("keeps everything while the estimate is within 70% of the cap", () => {
    const plan = planReview(budgetFiles, {
      maxTokensPerReview: Math.ceil(13_721 / BUDGET_FILL_RATIO),
      maxFiles: 10,
    });
    expect(plan.skipped).toEqual([]);
    expect(plan.estimatedInputTokens).toBe(13_721);
  });

  it("treats an estimate exactly at 70% as fitting", () => {
    const plan = planReview(
      budgetFiles,
      { maxTokensPerReview: 1_000, maxFiles: 10 },
      { estimateFileTokens: () => 100 },
    );
    expect(plan.skipped).toEqual([]);
    expect(plan.estimatedInputTokens).toBe(700);
  });

  it("drops files lowest risk weight first, then largest first, until the plan fits", () => {
    // Limit 7000: notes (w1) → 11914, e2e (w1) → 11527, big-table (w2, larger) → 6057.
    const plan = planReview(budgetFiles, { maxTokensPerReview: 10_000, maxFiles: 10 });
    expect(plan.skipped).toEqual([
      { path: "docs/notes.md", reason: "budget" },
      { path: "test/e2e.ts", reason: "budget" },
      { path: "src/lib/big-table.ts", reason: "budget" },
    ]);
    expect(plan.tasks[0]?.files.map((f) => f.path)).toEqual([
      "src/api/users.ts",
      "src/auth/login.ts",
      "src/handlers/order.ts",
      "src/lib/format.ts",
    ]);
    expect(plan.estimatedInputTokens).toBe(6_057);
    expect(plan.estimatedInputTokens).toBeLessThanOrEqual(10_000 * BUDGET_FILL_RATIO);
    expect(plan.tasks[0]?.budget).toBe(10_000);
  });

  it("trims files beyond maxFiles in the same risk order", () => {
    const plan = planReview(budgetFiles, { maxTokensPerReview: 1_000_000, maxFiles: 3 });
    expect(plan.skipped).toEqual([
      { path: "docs/notes.md", reason: "max_files" },
      { path: "test/e2e.ts", reason: "max_files" },
      { path: "src/lib/big-table.ts", reason: "max_files" },
      { path: "src/lib/format.ts", reason: "max_files" },
    ]);
    expect(plan.tasks[0]?.files.map((f) => f.path)).toEqual([
      "src/api/users.ts",
      "src/auth/login.ts",
      "src/handlers/order.ts",
    ]);
  });

  it("applies maxFiles before the token budget", () => {
    // maxFiles drops notes and e2e; limit 4200 then drops big-table, format, order, users.
    const plan = planReview(budgetFiles, { maxTokensPerReview: 6_000, maxFiles: 5 });
    expect(plan.skipped).toEqual([
      { path: "docs/notes.md", reason: "max_files" },
      { path: "test/e2e.ts", reason: "max_files" },
      { path: "src/lib/big-table.ts", reason: "budget" },
      { path: "src/lib/format.ts", reason: "budget" },
      { path: "src/handlers/order.ts", reason: "budget" },
      { path: "src/api/users.ts", reason: "budget" },
    ]);
    expect(plan.tasks[0]?.files.map((f) => f.path)).toEqual(["src/auth/login.ts"]);
    expect(plan.estimatedInputTokens).toBe(746);
  });

  it("returns an empty task when nothing fits", () => {
    const plan = planReview(budgetFiles, { maxTokensPerReview: 100, maxFiles: 10 });
    expect(plan.tasks).toEqual([{ id: "task-1", files: [], budget: 100 }]);
    expect(plan.skipped).toHaveLength(7);
    expect(plan.estimatedInputTokens).toBe(0);
    expect(plan.hotspots).toEqual([]);
  });

  it("returns hotspots (highest weight plus files with signals) and the complexity score", () => {
    const plan = planReview(fixture("risk-signals"), ROOMY);
    const hotspots = plan.hotspots.map((h) => h.path);
    // lib/secret.ts is the only weight-5 file; every file with a signal follows.
    expect(hotspots[0]).toBe("lib/secret.ts");
    expect(hotspots).toContain("lib/injection.md");
    expect(hotspots).toContain("db/migrations/0005_drop.sql");
    expect(hotspots).not.toContain("lib/clean.ts");
    expect(plan.hotspots.find((h) => h.path === "lib/injection.md")?.signals[0]?.name).toBe(
      "prompt_injection",
    );
    expect(plan.complexityScore).toBe(6);
  });

  it("ranks the highest-weight files as hotspots even without signals", () => {
    const plan = planReview(budgetFiles, ROOMY);
    expect(plan.hotspots.map((h) => h.path)).toEqual(["src/auth/login.ts"]);
    expect(plan.complexityScore).toBe(4); // 7 files (+1), 750 lines (+3)
  });

  it("only reports hotspots for files that stay in the plan", () => {
    const plan = planReview(fixture("risk-signals"), {
      maxTokensPerReview: 1_000_000,
      maxFiles: 1,
    });
    expect(plan.tasks[0]?.files.map((f) => f.path)).toEqual(["lib/secret.ts"]);
    expect(plan.hotspots.map((h) => h.path)).toEqual(["lib/secret.ts"]);
  });
});

describe("createPathFilter", () => {
  it("anchors patterns with a leading slash to the repo root", () => {
    const isExcluded = createPathFilter(["/generated/**"]);
    expect(isExcluded("generated/a.ts")).toBe(true);
    expect(isExcluded("src/generated/a.ts")).toBe(false);
  });
});

describe("estimateTokens", () => {
  it("is ceil(chars / 3.5)", () => {
    expect(estimateTokens("")).toBe(0);
    expect(estimateTokens("abc")).toBe(1);
    expect(estimateTokens("abcdefg")).toBe(2);
    expect(estimateTokens("abcdefgh")).toBe(3);
    expect(estimateTokens("x".repeat(350))).toBe(100);
  });
});

/** A diff adding one line to each of `paths`. */
const diffOf = (...paths: string[]) =>
  parseDiff(
    paths
      .map(
        (path) =>
          `diff --git a/${path} b/${path}\n--- a/${path}\n+++ b/${path}\n@@ -1,1 +1,2 @@\n line\n+added\n`,
      )
      .join(""),
  );

const pathsOf = (files: readonly { path: string }[]) => files.map((f) => f.path);

/** Every included file is in at least one check type. */
function expectFullCoverage(plan: ReturnType<typeof planChecks>) {
  const covered = new Set(plan.checks.flatMap((c) => pathsOf(c.files)));
  const included = new Set(plan.checks.flatMap((c) => c.groups.flatMap((g) => pathsOf(g.files))));
  expect(covered).toEqual(included);
  return covered;
}

describe("planChecks", () => {
  it("plans stability alone over a docs-only change", () => {
    const plan = planChecks(diffOf("README.md", "docs/guide.md", "config/app.yaml"), ROOMY);
    expect(plan.checks.map((c) => c.type)).toEqual(["stability"]);
    expect(pathsOf(plan.checks[0]!.files)).toEqual([
      "README.md",
      "docs/guide.md",
      "config/app.yaml",
    ]);
    expect(expectFullCoverage(plan).size).toBe(3);
  });

  it("leaves performance out of a test-only change", () => {
    const plan = planChecks(
      diffOf("src/a.test.ts", "pkg/b_test.go", "tests/test_c.py", "src/test/java/DTest.java"),
      ROOMY,
    );
    expect(plan.checks.map((c) => c.type)).toEqual(["security", "stability", "compatibility"]);
    for (const check of plan.checks) expect(check.files).toHaveLength(4);
  });

  it("covers every file of a mixed change, sending files outside any rubric language to stability", () => {
    const plan = planChecks(
      diffOf("src/api.ts", "src/api.test.ts", "docs/api.md", ".github/workflows/ci.yml"),
      ROOMY,
    );
    const byType = Object.fromEntries(plan.checks.map((c) => [c.type, pathsOf(c.files)]));
    expect(byType).toEqual({
      security: ["src/api.ts", "src/api.test.ts", ".github/workflows/ci.yml"],
      stability: ["src/api.ts", "src/api.test.ts", "docs/api.md", ".github/workflows/ci.yml"],
      performance: ["src/api.ts", ".github/workflows/ci.yml"],
      compatibility: ["src/api.ts", "src/api.test.ts", ".github/workflows/ci.yml"],
    });
    expect(expectFullCoverage(plan)).toEqual(
      new Set(["src/api.ts", "src/api.test.ts", "docs/api.md", ".github/workflows/ci.yml"]),
    );
  });

  it("gives each check type its finding categories", () => {
    const plan = planChecks(diffOf("src/a.ts"), ROOMY, { maintainability: true });
    expect(Object.fromEntries(plan.checks.map((c) => [c.type, c.categories]))).toEqual({
      security: ["security"],
      stability: ["correctness", "concurrency", "resources", "error-handling"],
      performance: ["performance"],
      compatibility: ["breaking-change", "tests"],
      maintainability: [],
    });
  });

  it("plans maintainability only when enabled", () => {
    expect(planChecks(diffOf("src/a.ts"), ROOMY).checks.map((c) => c.type)).not.toContain(
      "maintainability",
    );
  });

  it("plans nothing when every file is skipped", () => {
    const plan = planChecks(diffOf("pnpm-lock.yaml", "dist/x.js"), ROOMY);
    expect(plan.checks).toEqual([]);
    expect(plan.skipped.map((s) => s.reason)).toEqual(["excluded", "excluded"]);
  });

  it("reuses planReview's exclusions, maxFiles and budget", () => {
    const profile = { maxTokensPerReview: 4_000, maxFiles: 5 };
    const review = planReview(budgetFiles, profile);
    const checks = planChecks(budgetFiles, profile);
    expect(checks.skipped).toEqual(review.skipped);
    expect(checks.estimatedInputTokens).toBe(review.estimatedInputTokens);
    expect(checks.hotspots).toEqual(review.hotspots);
    expect(checks.complexityScore).toBe(review.complexityScore);
    expect(expectFullCoverage(checks)).toEqual(new Set(pathsOf(review.tasks[0]!.files)));
  });

  it("keeps a check type in one group up to 20 files", () => {
    const paths = Array.from({ length: 20 }, (_, i) => `src/m${i}/f.ts`);
    const plan = planChecks(diffOf(...paths), ROOMY);
    for (const check of plan.checks) {
      expect(check.groups).toEqual([
        { id: `${check.type}-1`, files: check.files, budget: ROOMY.maxTokensPerReview },
      ]);
    }
  });

  it("groups more than 20 files by directory, at most 20 per group", () => {
    const paths = [
      ...Array.from({ length: 12 }, (_, i) => `src/api/f${i}.ts`),
      ...Array.from({ length: 12 }, (_, i) => `src/auth/f${i}.ts`),
      ...Array.from({ length: 25 }, (_, i) => `lib/big/f${i}.ts`),
    ];
    const plan = planChecks(diffOf(...paths), ROOMY);
    const security = plan.checks.find((c) => c.type === "security")!;
    expect(security.groups.map((g) => g.id)).toEqual(["security-1", "security-2", "security-3"]);
    const dirs = security.groups.map((g) => [
      ...new Set(g.files.map((f) => f.path.slice(0, f.path.lastIndexOf("/")))),
    ]);
    // lib/big's 25 files split at 20; its last 5 share a group with src/api's 12.
    expect(dirs).toEqual([["lib/big"], ["lib/big", "src/api"], ["src/auth"]]);
    expect(security.groups.map((g) => g.files.length)).toEqual([20, 17, 12]);
    expect(security.groups.flatMap((g) => pathsOf(g.files)).sort()).toEqual([...paths].sort());
  });
});

